"""Area labels (neighbourhoods, towns, villages) for both city maps.
Shenzhen: real km -> map via the OSM places already placed by the metro fit
(global affine + inverse-distance residual correction). Huizhou: the anchor
warp from gen_hz_places.py. Writes client/src/areas.ts. Data © OSM, ODbL."""
import json, math, re, sys
from pathlib import Path
import numpy as np
try:  # English fallback for names without name:en (pip install pypinyin)
    from pypinyin import lazy_pinyin
except ImportError:
    lazy_pinyin = None
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import gen_hz_places as hz  # noqa: E402

src = (ROOT / "client/src/places-sz.ts").read_text()
rows = re.findall(r'P\("([^"]+)","[^"]+","\w+",(-?[\d.]+),(-?[\d.]+),(-?[\d.]+),(-?[\d.]+)', src)
osm = {p["id"]: p for p in json.loads((ROOT / "tools/metro/sz-osm-places.json").read_text())["places"]}
anc = [(float(x), float(z), float(kx), float(ky)) for pid, x, z, kx, ky in rows]
lat0 = np.mean([osm[pid]["lat"] + float(ky) / 110.57 for pid, x, z, kx, ky in rows if pid in osm])
kxs = [(osm[pid]["lon"], float(kx)) for pid, x, z, kx, ky in rows if pid in osm]
KX = 111.32 * math.cos(math.radians(lat0))
lon0 = np.mean([lon - kx / KX for lon, kx in kxs])
A = np.array([[a[2], a[3], 1] for a in anc]); B = np.array([[a[0], a[1]] for a in anc])
M, *_ = np.linalg.lstsq(A, B, rcond=None)
res = B - A @ M
def sz_xy(lat, lon):
    X, Y = (lon - lon0) * KX, -(lat - lat0) * 110.57
    base = np.array([X, Y, 1]) @ M
    d = np.hypot(A[:, 0] - X, A[:, 1] - Y)
    idx = np.argsort(d)[:5]; w = 1 / np.maximum(d[idx], 0.3) ** 2
    corr = (res[idx] * w[:, None]).sum(0) / w.sum()
    fade = min(1, 3 / max(1e-6, d[idx[0]]))  # far from any anchor: trust the affine
    return float(base[0] + corr[0] * fade), float(base[1] + corr[1] * fade)

def sz_coast(x): return 16.6 + math.sin(x * 0.1) * 1.1 + math.sin(x * 0.23 + 1.7) * 0.7
RANK = {"town": 0, "suburb": 1, "quarter": 2, "neighbourhood": 3, "residential": 4, "village": 5, "wood": 3}
data = json.loads((HERE / "areas-osm.json").read_text())
def game_locs(ck):
    s = (ROOT / "client/src/data.ts").read_text()
    blk = s[s.index("const SZ_LOCS" if ck == "sz" else "const HZ_LOCS"):]
    blk = blk[:blk.index("\n];")]
    return [(float(a), float(b)) for a, b in re.findall(r"x: (-?[\d.]+), z: (-?[\d.]+)", blk)]
out = []
for ck in ("sz", "hz"):
    taken = game_locs(ck)  # keep clear of game locations; real-place pins only block very close
    cells = {}
    for r in sorted(data[ck], key=lambda r: (RANK.get(r["kind"], 9), -r["area"])):
        name = r["name"].strip()
        if not re.search(r"[一-鿿]", name) or len(name) > 8 or re.search(r"社区$|居委会|工业区$|开发区$", name) and r["kind"] not in ("town", "suburb"): continue
        if ck == "sz": x, z = sz_xy(r["lat"], r["lon"]); coast = sz_coast(x)
        else: x, z = hz.to_xy(*hz.to_km(r["lat"], r["lon"])); coast = hz.coast_z(x)
        if abs(x) > 36.5 or z < -21 or z > coast - 0.8: continue
        big = r["kind"] in ("town", "suburb")
        if any(math.dist((x, z), t) < (1.2 if big else 1.6) for t in taken): continue
        cell = (round(x / (4.5 if big else 2.6)), round(z / (4.5 if big else 2.6)), big)
        if cell in cells: continue
        cells[cell] = 1; taken.append((x, z))
        en = r.get("en")
        if not en and lazy_pinyin:
            suf = next(((zh, e) for zh, e in (("街道", " Subdistrict"), ("社区", " Community"), ("新村", " New Village"), ("镇", " Town"), ("村", " Village"), ("区", " District")) if name.endswith(zh) and len(name) > len(zh)), ("", ""))
            core = name[: len(name) - len(suf[0])] if suf[0] else name
            en = "".join(lazy_pinyin(core)).capitalize() + suf[1]
        out.append({"c": ck, "n": name, "e": en, "k": "big" if big else "small", "x": round(x, 2), "z": round(z, 2)})
    print(ck, sum(1 for o in out if o["c"] == ck), "big", sum(1 for o in out if o["c"] == ck and o["k"] == "big"))
L = ["// GENERATED by tools/hz/gen_areas.py — neighbourhood / town / village names (OpenStreetMap, ODbL)",
     "// placed on the city maps, for the map's area labels over filler blocks and woods.",
     "export interface AreaLabel { c: \"sz\" | \"hz\"; n: string; e?: string | null; k: \"big\" | \"small\"; x: number; z: number }",
     "export const AREA_LABELS: AreaLabel[] = " + json.dumps(out, ensure_ascii=False) + ";", ""]
(ROOT / "client/src/areas.ts").write_text("\n".join(L))
print("lat0", lat0, "lon0", lon0)
for o in out:
    if o["n"] in ("白石洲", "华强北", "蛇口", "沙头角", "布吉", "南头", "西乡", "坂田", "大鹏", "惠阳", "淡水", "陈江", "平海"): print(o)
