"""Real skyline for the map's filler blocks. Each filler grid cell (2.8
map units, the same grid MapView walks) gets the count of tall buildings
(>= 24 m) that fall in it and their 90th-percentile height, from
buildings-osm.json (OpenStreetMap, ODbL). Shenzhen points go through the
same affine + residual fit as the area labels; Huizhou through the anchor
warp. Writes client/src/skyline.ts."""
import json, math, re, sys
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "tools/hz"))
import gen_hz_places as hz  # noqa: E402
sys.path.insert(0, str(ROOT / "tools/hk"))
import gen_hk_places as hk  # noqa: E402

# --- Shenzhen: real km -> map (same fit as tools/hz/gen_areas.py) ---
src = (ROOT / "client/src/places-sz.ts").read_text()
rows = re.findall(r'P\("([^"]+)","[^"]+","\w+",(-?[\d.]+),(-?[\d.]+),(-?[\d.]+),(-?[\d.]+)', src)
rows = [r for r in rows if not r[0].startswith("x")]  # rows added by add_sz_places.py are not fit anchors
osm = {p["id"]: p for p in json.loads((ROOT / "tools/metro/sz-osm-places.json").read_text())["places"]}
anc = [(float(x), float(z), float(kx), float(ky)) for pid, x, z, kx, ky in rows]
lat0 = np.mean([osm[pid]["lat"] + float(ky) / 110.57 for pid, x, z, kx, ky in rows if pid in osm])
KX = 111.32 * math.cos(math.radians(lat0))
lon0 = np.mean([osm[pid]["lon"] - float(kx) / KX for pid, x, z, kx, ky in rows if pid in osm])
A = np.array([[a[2], a[3], 1] for a in anc]); B = np.array([[a[0], a[1]] for a in anc])
M, *_ = np.linalg.lstsq(A, B, rcond=None)
res = B - A @ M
def sz_xy(lat, lon):
    X, Y = (lon - lon0) * KX, -(lat - lat0) * 110.57
    base = np.array([X, Y, 1]) @ M
    d = np.hypot(A[:, 0] - X, A[:, 1] - Y)
    idx = np.argsort(d)[:5]; w = 1 / np.maximum(d[idx], 0.3) ** 2
    corr = (res[idx] * w[:, None]).sum(0) / w.sum()
    fade = min(1, 3 / max(1e-6, d[idx[0]]))
    return float(base[0] + corr[0] * fade), float(base[1] + corr[1] * fade)

STEP = 2.8
data = json.loads((HERE / "buildings-osm.json").read_text())
import proj  # noqa: E402
from shapely.geometry import Point
from shapely.prepared import prep
ON_LAND = {ck: prep(proj._land(ck).buffer(0.2)) for ck in ("sz", "hz", "hk")}
out = {}
for ck in ("sz", "hz", "hk"):
    cells = {}
    for b in data.get(ck, []):
        x, z = sz_xy(b["lat"], b["lon"]) if ck == "sz" else hk.to_xy(*hk.to_km(b["lat"], b["lon"])) if ck == "hk" else hz.to_xy(*hz.to_km(b["lat"], b["lon"]))
        if abs(x) > 38 or z < -22 or not ON_LAND[ck].contains(Point(x, z)): continue
        key = f"{round((x + 36) / STEP)},{round((z + 20) / STEP)}"
        cells.setdefault(key, []).append(b["h"])
    out[ck] = {k: [len(v), int(np.percentile(v, 90))] for k, v in cells.items()}
    print(ck, len(data.get(ck, [])), "buildings ->", len(out[ck]), "cells", file=sys.stderr)
body = ",\n".join(f'  {ck}: {json.dumps(out[ck], separators=(",", ":"))}' for ck in out)
(ROOT / "client/src/skyline.ts").write_text(
    "/* GENERATED by tools/buildings/gen_skyline.py — do not edit.\n"
    "   Real skyline per filler grid cell (2.8 map units, origin -36/-20):\n"
    "   [number of buildings >= 24 m, their 90th-percentile height in m].\n"
    "   Data © OpenStreetMap contributors, ODbL. */\n"
    "export const SKYLINE: Record<\"sz\" | \"hz\" | \"hk\", Record<string, [number, number]>> = {\n" + body + ",\n};\n")
